import * as T from './nexus-fabric-60.mjs';
import * as C from './nexus-fabric-70.mjs';
import * as D from './nexus-fabric-90.mjs';
import * as M from './nexus-fabric-100.mjs';
import assert from 'node:assert/strict';
const pub={kty:'EC',crv:'P-256',x:'x',y:'y'};
const cert=T.makeCertificate({classId:'class-A',nodeId:M.nodeIdFor(pub),publicKey:pub,role:'teacher',issuerId:'teacher-1'});
let a=M.authorizeRelay({certificate:cert,classId:'class-A'}); assert.equal(a.ok,true);
assert.equal(M.authorizeRelay({certificate:cert,classId:'class-B'}).ok,false);
const e1={id:'e1',nodeId:'A',vc:{A:1},payload:1};
const e2={id:'e2',nodeId:'A',vc:{A:2},payload:2};
assert.equal(M.reconcile({applied:{},incoming:[e2]}).ready.length,0);
assert.equal(M.reconcile({applied:{},incoming:[e1,e2]}).ready.length,2);
const m=D.manifestFor(new TextEncoder().encode('hello world'),{name:'x'});
const chunks=D.chunkBytes(new TextEncoder().encode('hello world'),m.chunkSize); const store=new Map(); store.set(m.chunks[0].hash,chunks[0]);
assert.equal(D.assemble(m,store).ok,true);
const route=M.routeEvent({event:e1,from:'A',peers:[{nodeId:'B',capabilityScore:2}],certificate:cert,classId:'class-A'}); assert.deepEqual(route.peers,['B']);
assert.equal(M.health({}).status,'converged');
console.log('FABRIC 100 TESTS: PASS');
