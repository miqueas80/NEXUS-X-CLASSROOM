import assert from 'node:assert/strict';
import * as F from './nexus-fabric-50.mjs';
import * as X from './nexus-fabric-70.mjs';
const a={id:'a1',nodeId:'A',vc:{A:1},payload:{x:1}};
const b={id:'b1',nodeId:'B',vc:{A:1,B:1},payload:{x:2}};
const c={id:'c1',nodeId:'C',vc:{A:2,C:1},payload:{x:3}};
assert.equal(X.causalReady(a,{}),true);
assert.equal(X.causalReady(b,{A:1}),true);
assert.equal(X.causalReady(c,{A:1}),false);
const d=X.causalDrain([b,a],{}); assert.deepEqual(d.ready.map(x=>x.id),['a1','b1']);
const r=X.relayEnvelope({event:a,from:'A'}); const rr=X.acceptRelay(r,{nodeId:'B'}); assert.equal(rr.ok,true); assert.equal(rr.forward.ttl,X.DEFAULT_TTL-1);
assert.equal(X.acceptRelay({...r,hops:['A']},{nodeId:'A'}).reason,'loop');
assert.equal(X.acceptRelay({...r,ttl:0},{nodeId:'B'}).reason,'ttl');
assert.deepEqual(X.missingChunks(5,[0,2,4]),[1,3]);
assert.equal(X.chunkPlan(50000,24000).length,3);
const manifest=X.fileManifest({id:'sha256:x:50000:f',size:50000,chunkSize:24000,sha256:'x'}); assert.equal(manifest.chunks,3);
const pk={kty:'EC',crv:'P-256',x:'x',y:'y'}; const bind=X.trustBind('N',pk); assert.equal(X.verifyNodeBinding({...bind,publicKey:pk}),true);
const m=X.materialize([{...a,entityId:'e',vc:{A:1}},{...c,entityId:'e',vc:{A:2,C:1}}]); assert.equal(m.conflicts.length,0);
const q=X.materialize([{id:'z1',entityId:'e',nodeId:'A',vc:{A:1},payload:1},{id:'z2',entityId:'e',nodeId:'B',vc:{B:1},payload:2}]); assert.equal(q.conflicts.length,1);
