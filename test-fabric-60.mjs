import assert from 'node:assert/strict';
import {fingerprint,nodeBinding,makeCertificate,certificateValid,authorize,applyRevocation,classifyPeer,canRole} from './nexus-fabric-60.mjs';
const pub={kty:'EC',crv:'P-256',x:'abc',y:'xyz'};
const fp=fingerprint(pub);assert.equal(fp,fingerprint({...pub}));
assert.equal(nodeBinding('n1',pub).fingerprint,fp);
const cert=makeCertificate({classId:'C1',nodeId:'n1',publicKey:pub,role:'student',issuerId:'teacher',issuedAt:100});
assert.equal(certificateValid(cert,200),true);
assert.equal(classifyPeer('C1',cert),'member');
assert.equal(authorize({certificate:cert,action:'submit',classId:'C1'}).ok,true);
assert.equal(authorize({certificate:cert,action:'grade',classId:'C1'}).reason,'role');
assert.equal(authorize({certificate:cert,action:'read',classId:'C2'}).reason,'class');
assert.equal(canRole('teacher','revoke'),true);
assert.equal(canRole('guest','write'),false);
const revoked=[{serial:cert.serial,effectiveAt:150}];
assert.equal(applyRevocation(revoked,cert,200),true);
assert.equal(authorize({certificate:cert,action:'read',classId:'C1',revokedSerials:new Set([cert.serial])}).reason,'revoked');
assert.equal(classifyPeer('C1',cert,revoked,200),'revoked');
const expired=makeCertificate({classId:'C1',nodeId:'n2',publicKey:pub,role:'guest',issuerId:'teacher',expiresAt:100});
assert.equal(certificateValid(expired,101),false);
console.log('FABRIC 60 TRUST TESTS: PASS');
